def main() -> None:
    catalog: dict[str, list[dict]] = {}
    for cat, items in TOPICS.items():
        if len(items) != 15:
            raise SystemExit(f"{cat} has {len(items)} topics, expected 15")
        catalog[cat] = [build_article(item) for item in items]
        for article in catalog[cat]:
            if word_count(article["content"]) < 100:
                raise SystemExit(f"{article['id']} under 100 words")

    OUT.write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    total = sum(len(v) for v in catalog.values())
    print(f"Wrote {OUT} with {len(catalog)} categories, {total} articles")
    for cat, arts in catalog.items():
        lengths = [word_count(a["content"]) for a in arts]
        print(f"  {cat}: {len(arts)} topics, words {min(lengths)}–{max(lengths)}")


if __name__ == "__main__":
    main()
