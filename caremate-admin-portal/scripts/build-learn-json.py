def expand(points: list[str]) -> str:
    """Turn teaching points into multi-paragraph prose with disclaimer."""
    chunks: list[str] = []
    # Group points into ~3 paragraphs
    for i in range(0, len(points), 2):
        pair = points[i : i + 2]
        chunks.append(" ".join(pair))
    body = "\n\n".join(chunks)
    body = f"{body}\n\n{DISCLAIMER}"
    # Guarantee ≥100 words with a stable educational closer if needed
    while word_count(body) < 100:
        body += (
            " Write down questions before clinic visits, bring your medicine list, "
            "and share how symptoms change across days so clinicians can advise more accurately."
        )
    return body


def word_count(text: str) -> int:
    return len(re.findall(r"\b\w+\b", text))


def build_article(item: tuple[str, str, str, list[str]]) -> dict:
    id_, title, summary, points = item
    content = expand(points)
    assert word_count(content) >= 100, f"{id_}: {word_count(content)}"
    return {"id": id_, "title": title, "summary": summary, "content": content}


